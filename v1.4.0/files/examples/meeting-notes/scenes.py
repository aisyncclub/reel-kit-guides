#   scene(프레임, 단어, 부품, top=위 꼬리표, foot=(아래 칩, 뜨는 단어))   프레임 1 = 첫 줄(훅 카드 뒤)
#   그 프레임 음성에서 그 단어가 나올 때 도형이 다음 모양으로 바뀐다. 0 = 프레임 첫 단어
#   부품: doc · chips · slots · columns · badge · checklist · table · gather · number · compare · typing
#   쓰는 법: .claude/skills/make-reel/references/morph.md
#
# 비유는 편 전체에 하나 — 「세 칸」. 긴 문서가 세 칸으로 바뀌는 이야기다.

# 1번(첫 줄)도 쓸 수 있다: 훅 카드(첫 1.4초)가 빠지면 바로 도형이 이어받아 빈 화면이 없다
scene(1, 0, typing("이 회의 내용 정리해 줘", at="클로드", title="클로드에게", reply=8), top="회의 끝나고")
scene(1, "회의가", chips(["회의가 길어서?"], strike="아니에요", title="정리가 느린 이유"), top="그런데 느린 건")

scene(2, 0, doc("회의 메모", lines=11), top="저도 이렇게")
scene(2, "요약만", doc("긴 요약", lines=17), top="통째로 넣으면", foot=("또 읽어야 해요", "시켰거든요"))

scene(3, 0, chips(["프롬프트 공식", "역할 부여"], strike="몰라도", title="이런 말은 몰라도 돼요"), top="어려운 말은")
scene(3, "뽑을지만", slots(["?", "?", "?"], label=("뽑을 칸부터", "정하면")), top="먼저 정할 것")

scene(4, "세", columns([("결정", "정해진 것"), ("할 일", "누가 · 언제"), ("질문", "안 끝난 것")],
                      picks=["결정", "할", "질문"]), top="딱 세 칸", foot=("이 세 칸만 채우면 끝", "질문"))

DOTS[5] = dots(3, 0)
PROMPT[5] = prompt("이렇게 시켰습니다", "회의에서 *정해진 것만* 한 줄씩 뽑아 줘")
scene(5, "결정", badge(1, "결정"))
scene(5, "회의에서", checklist("결정 · 예시", ["출시일은 금요일", "디자인은 B안", "예산은 그대로"], fill="정해진",
                              count=("3줄", "줄씩")), top="정해진 것만", foot=("한 줄씩", "뽑아"))

DOTS[6] = dots(3, 1)
PROMPT[6] = prompt("이렇게 시켰습니다", "누가 · 언제까지 · 무엇을 *표로* 정리해 줘")
scene(6, "할", badge(2, "할 일"))
scene(6, "누가", table(["누가", "언제까지", "무엇을"],
                      [("민지", "금요일", "시안 정리"), ("준호", "다음 주", "견적 받기"), ("나", "내일", "공지 쓰기")],
                      picks=["누가", "언제까지", "무엇을"], fill="표로"), top="표로 받기")

DOTS[7] = dots(3, 2)
PROMPT[7] = prompt("이렇게 시켰습니다", "결론 *안 난 것만* 따로 모아 줘")
scene(7, "질문", badge(3, "질문"))
scene(7, "결론이", gather(["로고 색은?", "외주 줄까?", "일정 당길까?"], "다음 회의에서 이어 갈 것", pull="모읍니다"),
      top="결론 안 난 것만")

scene(8, "긴", doc("긴 요약", lines=15, cross="대신"), top="이제 이건 그만")
scene(8, "다음", slots(["결정", "할 일", "질문"], done=True, label=("다음 회의에 바로", "바로")), foot=("세 칸이 남아요", "칸이"))
